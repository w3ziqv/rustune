#!/usr/bin/env python3
"""Generate the Firefox adapter from the same MusicKit implementation as Chromium."""
from pathlib import Path
import zipfile
root = Path(__file__).resolve().parent.parent
source = (root / 'src/backend/musickit.js').read_text()
source = source.replace("  const mk = __RUSTUNE_INSTANCE__;", "  if (window.rustune?.version === 2) return true;\n  const mk = MusicKit.getInstance();")
(root / 'extensions/firefox/adapter.js').write_text('// Generated by scripts/package-firefox.py; edit src/backend/musickit.js.\n' + source)
out = root / 'dist'
out.mkdir(exist_ok=True)
with zipfile.ZipFile(out / 'rustune-firefox.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
    for name in ['manifest.json','background.js','adapter.js']:
        archive.write(root / 'extensions/firefox' / name, name)
    archive.write(root / 'LICENSE', 'LICENSE')
print(out / 'rustune-firefox.zip')
